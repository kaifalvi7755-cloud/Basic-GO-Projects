package main

import "fmt"

func main() {
	println("======================================================================================")
    println("                                REVERSE ARRAY                                         ")
    println("======================================================================================")
	arr := []int{1, 2, 3, 4}
	for i := len(arr) - 1; i >= 0; i-- {
		fmt.Println(arr[i],"")
	}
}